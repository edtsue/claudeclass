// ClaudeClass service worker — network-first (fresh when online, cached offline).
const CACHE = 'claudeclass-v1';
const PRECACHE = ['/', '/index.html', '/assets/styles.css', '/assets/app.mjs', '/assets/content.mjs', '/assets/config.mjs'];

self.addEventListener('install', (e) => {
  self.skipWaiting();
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE).catch(() => {})));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;      // let the browser handle CDN/fonts
  if (url.pathname.startsWith('/api/')) return;     // never cache API calls

  // Network-first: always try fresh, cache the result, fall back to cache offline.
  e.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
        return res;
      })
      .catch(() => caches.match(req).then((r) => r || caches.match('/index.html')))
  );
});
